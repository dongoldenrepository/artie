#!/usr/bin/env node
/**
 * migrate-to-unified.js
 * Merges three artie databases into one unified database.
 *
 * Usage (from the artie directory):
 *   node migrate-to-unified.js
 *
 * Prerequisites:
 *   1. wrangler-unified.toml has been created with the correct database_id
 *   2. artie-unified-db has been created and all migrations run
 *   3. wrangler.toml.bak exists (backup of the template wrangler.toml)
 */

const { execSync } = require('child_process')
const fs = require('fs')
const path = require('path')

// ─── Configuration ──────────────────────────────────────────────────────────

const SOURCES = [
  {
    subdomain:    'don',
    newArtistId:  1,
    db:           'artie-don-db',
    toml:         'wrangler-don.toml',
    idOffset:     0,
    imagePrefix:  'don/',
    imageBucket:  'artie-don-images',
  },
  {
    subdomain:    'kathy',
    newArtistId:  2,
    db:           'kathy-catalog-db',
    toml:         'wrangler-kathy.toml',
    idOffset:     100000,
    imagePrefix:  'kathy/',
    imageBucket:  'kathy-catalog-images',
  },
  {
    subdomain:    'mary',
    newArtistId:  3,
    db:           'artie-mlynch-db',
    toml:         'wrangler-mary.toml',
    idOffset:     200000,
    imagePrefix:  'mary/',
    imageBucket:  'mary-lynch-artie-images',
  },
]

const UNIFIED_DB   = 'artie-unified-db'
const UNIFIED_TOML = 'wrangler-unified.toml'
const BACKUP_TOML  = 'wrangler.toml.bak'
const SQL_FILE     = 'unified-migration.sql'

// ─── Helpers ────────────────────────────────────────────────────────────────

// Safe SQL string literal
function sq(val) {
  if (val === null || val === undefined) return 'NULL'
  return `'${String(val).replace(/'/g, "''")}'`
}

// Swap wrangler.toml and run a SELECT, return rows
function queryDB(db, toml, sql) {
  fs.copyFileSync(toml, 'wrangler.toml')
  try {
    const raw = execSync(
      `npx wrangler d1 execute "${db}" --remote --json --command=${JSON.stringify(sql)}`,
      { encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] }
    )
    // wrangler outputs status text + JSON array — extract the JSON
    const match = raw.match(/\[[\s\S]*\]/)
    if (!match) { console.warn('  ⚠ No JSON in output'); return [] }
    const parsed = JSON.parse(match[0])
    return parsed[0]?.results || []
  } catch (e) {
    console.error(`  ✗ Query failed on ${db}: ${sql.substring(0, 60)}`)
    console.error(e.stderr?.toString() || e.message)
    return []
  } finally {
    restoreToml()
  }
}

function restoreToml() {
  if (fs.existsSync(BACKUP_TOML)) fs.copyFileSync(BACKUP_TOML, 'wrangler.toml')
}

// ─── Generate SQL ────────────────────────────────────────────────────────────

function generateSQL(sources) {
  const lines = [
    '-- Unified migration generated by migrate-to-unified.js',
    '-- Safe to re-run (uses INSERT OR IGNORE)',
    '',
    'PRAGMA foreign_keys = OFF;',
    '',
  ]

  for (const source of sources) {
    const { subdomain, newArtistId, db, toml, idOffset } = source
    console.log(`\nQuerying ${subdomain} (${db})...`)

    lines.push(`-- ══════════════════════════════════════`)
    lines.push(`-- Artist: ${subdomain} (new id=${newArtistId}, offset=${idOffset})`)
    lines.push(`-- ══════════════════════════════════════`)
    lines.push('')

    // ── Artist ────────────────────────────────────────────────────────────
    console.log('  artists...')
    const artists = queryDB(db, toml, 'SELECT * FROM artists WHERE id = 1')
    for (const a of artists) {
      lines.push(
        `INSERT OR IGNORE INTO artists (id, name, email, bio, website, default_medium, artist_type, admin_password, subdomain, created_at) VALUES ` +
        `(${newArtistId}, ${sq(a.name)}, ${sq(a.email)}, ${sq(a.bio)}, ${sq(a.website)}, ` +
        `${sq(a.default_medium)}, ${sq(a.artist_type || 'painter')}, ${sq(a.admin_password)}, ${sq(subdomain)}, ${sq(a.created_at)});`
      )
    }
    lines.push('')

    // ── Genres ────────────────────────────────────────────────────────────
    console.log('  genres...')
    const genres = queryDB(db, toml, 'SELECT * FROM genres WHERE artist_id = 1')
    for (const g of genres) {
      lines.push(
        `INSERT OR IGNORE INTO genres (id, artist_id, name, color, tag_type, enabled) VALUES ` +
        `(${g.id + idOffset}, ${newArtistId}, ${sq(g.name)}, ${sq(g.color || '#6b7280')}, ` +
        `${sq(g.tag_type || 'subject')}, ${g.enabled ?? 1});`
      )
    }
    lines.push('')

    // ── Categories ────────────────────────────────────────────────────────
    console.log('  categories...')
    const cats = queryDB(db, toml, 'SELECT * FROM categories WHERE artist_id = 1')
    for (const c of cats) {
      lines.push(
        `INSERT OR IGNORE INTO categories (id, artist_id, name, color, is_printable, display_order) VALUES ` +
        `(${c.id + idOffset}, ${newArtistId}, ${sq(c.name)}, ${sq(c.color || '#6b7280')}, ` +
        `${c.is_printable ?? 0}, ${c.display_order ?? 0});`
      )
    }
    lines.push('')

    // ── Custom field definitions ───────────────────────────────────────────
    console.log('  custom fields...')
    const fields = queryDB(db, toml, 'SELECT * FROM custom_field_definitions WHERE artist_id = 1')
    for (const f of fields) {
      lines.push(
        `INSERT OR IGNORE INTO custom_field_definitions (id, artist_id, name, field_type, display_order) VALUES ` +
        `(${f.id + idOffset}, ${newArtistId}, ${sq(f.name)}, ${sq(f.field_type || 'text')}, ${f.display_order ?? 0});`
      )
    }
    lines.push('')

    // ── Artworks ──────────────────────────────────────────────────────────
    console.log('  artworks...')
    const artworks = queryDB(db, toml, 'SELECT * FROM artworks WHERE artist_id = 1')
    for (const a of artworks) {
      const catId = a.category_id != null ? a.category_id + idOffset : null
      // Prefix image key with artist subdomain
      const imageKey = a.image_key ? `${subdomain}/${a.image_key}` : null
      lines.push(
        `INSERT OR IGNORE INTO artworks (id, artist_id, title, medium, size, price, date_created, current_location, description, image_key, is_available, artwork_type, sort_order, category_id, created_at, updated_at) VALUES ` +
        `(${a.id + idOffset}, ${newArtistId}, ${sq(a.title)}, ${sq(a.medium)}, ${sq(a.size)}, ` +
        `${a.price != null ? a.price : 'NULL'}, ${sq(a.date_created)}, ${sq(a.current_location)}, ` +
        `${sq(a.description)}, ${sq(imageKey)}, ${a.is_available ?? 1}, ${sq(a.artwork_type || 'artwork')}, ` +
        `${a.sort_order ?? 0}, ${catId != null ? catId : 'NULL'}, ${sq(a.created_at)}, ${sq(a.updated_at)});`
      )
    }
    lines.push('')

    // ── Artwork genres (junction) ──────────────────────────────────────────
    console.log('  artwork tags...')
    const artworkGenres = queryDB(db, toml, 'SELECT * FROM artwork_genres')
    for (const ag of artworkGenres) {
      lines.push(
        `INSERT OR IGNORE INTO artwork_genres (artwork_id, category_id) VALUES ` +
        `(${ag.artwork_id + idOffset}, ${ag.category_id + idOffset});`
      )
    }
    lines.push('')

    // ── Artwork custom values ──────────────────────────────────────────────
    console.log('  custom field values...')
    const customVals = queryDB(db, toml, 'SELECT * FROM artwork_custom_values')
    for (const v of customVals) {
      lines.push(
        `INSERT OR IGNORE INTO artwork_custom_values (artwork_id, field_id, value) VALUES ` +
        `(${v.artwork_id + idOffset}, ${v.field_id + idOffset}, ${sq(v.value)});`
      )
    }
    lines.push('')

    // ── Artwork images (extra photos) ──────────────────────────────────────
    console.log('  artwork images...')
    const artworkImages = queryDB(db, toml, 'SELECT * FROM artwork_images')
    for (const img of artworkImages) {
      const imageKey = img.image_key ? `${subdomain}/${img.image_key}` : null
      lines.push(
        `INSERT OR IGNORE INTO artwork_images (id, artwork_id, image_key, caption, sort_order, created_at) VALUES ` +
        `(${img.id + idOffset}, ${img.artwork_id + idOffset}, ${sq(imageKey)}, ` +
        `${sq(img.caption)}, ${img.sort_order ?? 0}, ${sq(img.created_at)});`
      )
    }
    lines.push('')

    // ── Showings ──────────────────────────────────────────────────────────
    console.log('  showings...')
    const showings = queryDB(db, toml, 'SELECT * FROM showings')
    for (const s of showings) {
      lines.push(
        `INSERT OR IGNORE INTO showings (id, artwork_id, venue, location, start_date, end_date, notes, created_at) VALUES ` +
        `(${s.id + idOffset}, ${s.artwork_id + idOffset}, ${sq(s.venue)}, ${sq(s.location)}, ` +
        `${sq(s.start_date)}, ${sq(s.end_date)}, ${sq(s.notes)}, ${sq(s.created_at)});`
      )
    }
    lines.push('')

    // ── Awards ────────────────────────────────────────────────────────────
    console.log('  awards...')
    const awards = queryDB(db, toml, 'SELECT * FROM awards')
    for (const a of awards) {
      lines.push(
        `INSERT OR IGNORE INTO awards (id, artwork_id, title, organization, award_date, notes, created_at) VALUES ` +
        `(${a.id + idOffset}, ${a.artwork_id + idOffset}, ${sq(a.title)}, ${sq(a.organization)}, ` +
        `${sq(a.award_date)}, ${sq(a.notes)}, ${sq(a.created_at)});`
      )
    }
    lines.push('')

    // ── Prints ────────────────────────────────────────────────────────────
    console.log('  prints...')
    const prints = queryDB(db, toml, 'SELECT * FROM prints')
    for (const p of prints) {
      lines.push(
        `INSERT OR IGNORE INTO prints (id, artwork_id, size, medium, price, current_location, sold_to, is_available, notes, created_at) VALUES ` +
        `(${p.id + idOffset}, ${p.artwork_id + idOffset}, ${sq(p.size)}, ${sq(p.medium)}, ` +
        `${p.price != null ? p.price : 'NULL'}, ${sq(p.current_location)}, ${sq(p.sold_to)}, ` +
        `${p.is_available ?? 1}, ${sq(p.notes)}, ${sq(p.created_at)});`
      )
    }
    lines.push('')

    console.log(`  ✓ ${subdomain} done`)
  }

  lines.push('PRAGMA foreign_keys = ON;')
  lines.push('')
  return lines.join('\n')
}

// ─── Main ────────────────────────────────────────────────────────────────────

function main() {
  console.log('╔══════════════════════════════════════╗')
  console.log('║   Artie Unified Database Migration   ║')
  console.log('╚══════════════════════════════════════╝\n')

  if (!fs.existsSync(UNIFIED_TOML)) {
    console.error(`✗ ${UNIFIED_TOML} not found. Please create it first.`)
    process.exit(1)
  }

  // Generate SQL
  console.log('Step 1: Querying source databases...')
  const sql = generateSQL(SOURCES)

  // Write SQL file
  fs.writeFileSync(SQL_FILE, sql, 'utf8')
  console.log(`\nStep 2: SQL written to ${SQL_FILE} (${sql.length} bytes)`)

  // Execute against unified DB
  console.log(`\nStep 3: Importing into ${UNIFIED_DB}...`)
  fs.copyFileSync(UNIFIED_TOML, 'wrangler.toml')
  try {
    execSync(
      `npx wrangler d1 execute "${UNIFIED_DB}" --remote --file="${SQL_FILE}" --yes`,
      { encoding: 'utf8', stdio: 'inherit' }
    )
    console.log('\n✅ Migration complete!')
    console.log(`\nNext steps:`)
    console.log(`  1. Verify data: node migrate-to-unified.js --verify`)
    console.log(`  2. Copy R2 images (see DEPLOY.md for rclone instructions)`)
  } catch (e) {
    console.error('\n✗ Import failed. Check unified-migration.sql for issues.')
    process.exit(1)
  } finally {
    restoreToml()
  }
}

// --verify flag: print row counts from unified DB
if (process.argv.includes('--verify')) {
  console.log('Verifying unified database...\n')
  fs.copyFileSync(UNIFIED_TOML, 'wrangler.toml')
  const tables = ['artists', 'artworks', 'genres', 'categories', 'artwork_genres', 'prints', 'showings', 'awards']
  for (const t of tables) {
    try {
      const raw = execSync(
        `npx wrangler d1 execute "${UNIFIED_DB}" --remote --json --command="SELECT COUNT(*) as n FROM ${t}"`,
        { encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] }
      )
      const match = raw.match(/\[[\s\S]*\]/)
      if (match) {
        const parsed = JSON.parse(match[0])
        const count = parsed[0]?.results[0]?.n ?? '?'
        console.log(`  ${t.padEnd(30)} ${count} rows`)
      }
    } catch {}
  }
  restoreToml()
  process.exit(0)
}

main()
